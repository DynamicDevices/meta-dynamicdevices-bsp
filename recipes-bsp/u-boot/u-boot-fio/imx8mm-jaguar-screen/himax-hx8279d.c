static int hx8279d_init_sequence(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct mipi_dsi_device *dsi = plat->device;
	size_t i;
	int ret;

	for (i = 0; i < ARRAY_SIZE(st1010_init); i++) {
		u8 payload[2];

		if (st1010_init[i].delay_ms) {
			mdelay(st1010_init[i].delay_ms);
			continue;
		}
		payload[0] = st1010_init[i].cmd;
		payload[1] = st1010_init[i].data;
		ret = mipi_dsi_generic_write(dsi, payload, sizeof(payload));
		if (ret < 0) {
			dev_err(dev, "init command %zu failed: %d\n", i, ret);
			return ret;
		}
	}

	ret = mipi_dsi_dcs_exit_sleep_mode(dsi);
	if (ret < 0)
		return ret;
	mdelay(120);

	ret = mipi_dsi_dcs_set_display_on(dsi);
	if (ret < 0)
		return ret;
	mdelay(20);

	/*
	 * Match the working Linux panel lifecycle.  Its prepare callback sends
	 * DISPLAY_ON above, then the enable callback waits another 120 ms and
	 * sends DISPLAY_ON once more before the backlight is enabled.
	 */
	mdelay(120);
	ret = mipi_dsi_dcs_set_display_on(dsi);
	if (ret < 0)
		return ret;

	return 0;
}

static int hx8279d_enable_backlight(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct hx8279d_priv *priv = dev_get_priv(dev);
	int ret;

	ret = mipi_dsi_attach(plat->device);
	if (ret < 0)
		return ret;

	ret = hx8279d_init_sequence(dev);
	if (ret)
		return ret;

	return dm_gpio_set_value(&priv->backlight_enable, 1);
}

static int hx8279d_get_display_timing(struct udevice *dev,
				      struct display_timing *timing)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct mipi_dsi_device *dsi = plat->device;

	memcpy(timing, &st1010_timing, sizeof(*timing));

	/*
	 * The SEC-DSIM host creates its DSI device before requesting the
	 * panel timing.  Transfer the panel characteristics here, before the
	 * later mipi_dsi_attach() call validates the lane count.
	 */
	if (dsi) {
		dsi->lanes = plat->lanes;
		dsi->format = plat->format;
		dsi->mode_flags = plat->mode_flags;
	}

	return 0;
}

static int hx8279d_of_to_plat(struct udevice *dev)
{
	struct hx8279d_priv *priv = dev_get_priv(dev);
	int ret;

	ret = gpio_request_by_name(dev, "enable-gpios", 0,
				   &priv->panel_enable, GPIOD_IS_OUT);
	if (ret)
		return ret;

	ret = gpio_request_by_name(dev, "backlight-gpios", 0,
				   &priv->backlight_enable, GPIOD_IS_OUT);
	if (ret)
		return ret;

	return 0;
}

static int hx8279d_probe(struct udevice *dev)
{
	struct mipi_dsi_panel_plat *plat = dev_get_plat(dev);
	struct hx8279d_priv *priv = dev_get_priv(dev);
	int ret;

	/*
	 * DSI_EN_2 is a TPS22913B load-switch enable, not panel RESET.
	 * Force a real off interval so a warm reset cannot inherit controller
	 * state left by Linux or an earlier U-Boot attempt.
	 */
	ret = dm_gpio_set_value(&priv->panel_enable, 0);
	if (ret)
		return ret;
	mdelay(20);

	ret = dm_gpio_set_value(&priv->panel_enable, 1);
	if (ret)
		return ret;
	mdelay(10);

	plat->lanes = 4;
	plat->format = MIPI_DSI_FMT_RGB888;
	plat->mode_flags = MIPI_DSI_MODE_VIDEO |
			   MIPI_DSI_MODE_VIDEO_SYNC_PULSE |
			   MIPI_DSI_CLOCK_NON_CONTINUOUS |
			   MIPI_DSI_MODE_LPM;
	return 0;
}

static const struct panel_ops hx8279d_ops = {
	.enable_backlight = hx8279d_enable_backlight,
	.get_display_timing = hx8279d_get_display_timing,
};

static const struct udevice_id hx8279d_ids[] = {
	{ .compatible = "santek,st1010b3cyol" },
	{ .compatible = "himax,hx8279d" },
	{ }
};

U_BOOT_DRIVER(hx8279d_panel) = {
	.name = "hx8279d_panel",
	.id = UCLASS_PANEL,
	.of_match = hx8279d_ids,
	.ops = &hx8279d_ops,
	.of_to_plat = hx8279d_of_to_plat,
	.probe = hx8279d_probe,
	.plat_auto = sizeof(struct mipi_dsi_panel_plat),
	.priv_auto = sizeof(struct hx8279d_priv),
};
